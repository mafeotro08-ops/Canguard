-- Secreto TOTP cifrado (clave TOTP_KEY del .env), si está activo, último
-- intervalo de 30 s aceptado (para no reutilizar códigos) y fecha de activación.
ALTER TABLE Usuario ADD COLUMN IF NOT EXISTS TotpSecret          VARCHAR(255) NULL;
ALTER TABLE Usuario ADD COLUMN IF NOT EXISTS TotpActivo          BOOLEAN      NOT NULL DEFAULT FALSE;
ALTER TABLE Usuario ADD COLUMN IF NOT EXISTS TotpUltimoIntervalo BIGINT       NULL;
ALTER TABLE Usuario ADD COLUMN IF NOT EXISTS TotpActivadoEn      TIMESTAMP    NULL;

-- Códigos de respaldo de un solo uso (SHA-256 del código), por si se pierde el celular.
CREATE TABLE IF NOT EXISTS CodigoRespaldo (
    IdCodigoRespaldo INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdUsuario        INT        NOT NULL,
    CodigoHash       CHAR(64)   NOT NULL,
    UsadoEn          TIMESTAMP  NULL,
    FechaRegistro    TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FkCodigoRespaldoUsuario FOREIGN KEY (IdUsuario) REFERENCES Usuario(IdUsuario) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS IxCodigoRespaldoUsuario ON CodigoRespaldo (IdUsuario, UsadoEn);
